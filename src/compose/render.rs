/// Rewrite CRLF line endings as LF.
///
/// Every file rendered here is compared byte for byte: by `chaps sync`
/// against what is on disk, and by the tests against the golden fixture. The
/// templates are compiled in with `include_str!`, so on a Windows checkout
/// with git's default `core.autocrlf` they would arrive with CRLF and the
/// rendered file would differ from the same file rendered anywhere else.
/// Passing them through here once makes the output `\n` on every platform,
/// whatever the checkout did.
pub(crate) fn normalize_newlines(text: &str) -> String {
    text.replace("\r\n", "\n")
}

