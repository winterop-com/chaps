/// Render the base `compose.yml`.
///
/// With `spec.upstream` the body is chap-core's own `compose.ghcr.yml` at that
/// tag, byte for byte but for its line endings, behind the shared header line
/// plus one naming the tag; without it the copy compiled into the binary is
/// used as it is. Both renderings are a pure function of the project state,
/// which is what lets `chaps sync` treat `compose.yml` as an artifact.
pub fn render_base(spec: &BaseSpec) -> String {
    let Some(upstream) = &spec.upstream else {
        return BASE_TEMPLATE.clone();
    };
    let mut out = format!(
        "{GENERATED_HEADER}\n# chap-core compose.ghcr.yml at {}\n",
        upstream.tag
    );
    out.push_str(&normalize_newlines(&upstream.body));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// Render `compose.chaps.yml`: the chaps-owned settings that sit on top of
/// the fetched `compose.yml`.
///
/// It exists because the base file is upstream's, byte for byte, and because
/// `include:` cannot override a service the main file defines - only a
/// separate `-f` entry can. The `!override` tag (Compose 2.24.4+, which is why
/// that is this CLI's supported minimum) replaces chap's own `ports:` list
/// rather than adding to it, which is what keeps the API on exactly one host
/// port.
///
/// `api_port` is rendered as the `${CHAP_API_PORT:-...}` default, so the file
/// stands on its own while `.env` stays the way to change the port without
/// touching `.chaps/`.
///
/// `project_name` is the top-level `name:`, which is what keeps this
/// deployment's containers and volumes to itself; see [`project_name_block`].
///
/// The `environment:` block hands chap-core the registration key. Upstream's
/// `compose.ghcr.yml` passes only `CHAP_API_TOKEN` into the service, so a
/// deployment with authentication on has a chap-core that knows the API token
/// and not the key - and then rejects every model's `X-Service-Key` with a
/// 401. Compose merges `environment` maps across `-f` files additively, so
/// this adds the one variable without touching upstream's file. It is
/// rendered whether or not the deployment has a key: with none in `.env` the
/// variable arrives empty, which is what chap-core reads as "not set".
///
/// The same block sets `XDG_RUNTIME_DIR`. chap-core runs gunicorn 26, which
/// opens a control socket at `$XDG_RUNTIME_DIR/gunicorn.ctl` and falls back to
/// `$HOME/.gunicorn/` - a path the service's read-only root filesystem
/// refuses, so every start logs `Control server error: [Errno 30] Read-only
/// file system: '/home/chap'`. The server comes up either way; pointing the
/// socket at the writable `/tmp` tmpfs keeps that line out of the log. Only
/// the `chap` service needs it: the worker runs celery, not gunicorn.
///
/// `checkout` is a chap-core checkout the chap and worker images are built
/// from instead of pulled (`chaps init --source`). `pull_policy: build` makes
/// every `chaps up` build the checkout as it is now, which Docker's layer
/// cache keeps cheap when nothing changed, and makes `compose pull` skip them.
pub fn render_chaps_overlay(
    api_port: u16,
    project_name: Option<&str>,
    checkout: Option<&str>,
) -> String {
    let (chap_image, worker_image) = checkout_images(project_name);
    let (chap_build, worker_build) = match checkout {
        Some(path) => (
            format!(
                "\x20   image: {chap_image}\n\
                 \x20   build:\n\
                 \x20     context: {path}\n\
                 \x20   pull_policy: build\n"
            ),
            format!(
                "\x20 worker:\n\
                 \x20   image: {worker_image}\n\
                 \x20   build:\n\
                 \x20     context: {path}\n\
                 \x20     dockerfile: Dockerfile.worker\n\
                 \x20   pull_policy: build\n"
            ),
        ),
        None => (String::new(), String::new()),
    };
    format!(
        "{GENERATED_HEADER}\n\
         {}\
         services:\n\
         \x20 chap:\n\
         {chap_build}\
         \x20   ports: !override\n\
         \x20     - \"${{{API_PORT_ENV_VAR}:-{api_port}}}:8000\"\n\
         \x20   environment:\n\
         \x20     {REGISTRATION_KEY_ENV_VAR}: ${{{REGISTRATION_KEY_ENV_VAR}:-}}\n\
         \x20     # Keeps gunicorn's control socket off the read-only root; drop it once chap-core disables that socket.\n\
         \x20     XDG_RUNTIME_DIR: /tmp\n\
         {worker_build}",
        project_name_block(project_name)
    )
}

/// The image a chap-core checkout's API is built into, for a deployment
/// compose can make no project name out of.
pub const CHECKOUT_CHAP_IMAGE: &str = "chap-core-checkout:local";
/// The same for the worker.
pub const CHECKOUT_WORKER_IMAGE: &str = "chap-worker-checkout:local";

/// The images a chap-core checkout is built into: named after the compose
/// project, so two deployments built from two checkouts (two worktrees, say)
/// never overwrite each other's build.
pub fn checkout_images(project_name: Option<&str>) -> (String, String) {
    match project_name {
        Some(name) => (
            format!("{name}-chap:checkout"),
            format!("{name}-worker:checkout"),
        ),
        None => (
            CHECKOUT_CHAP_IMAGE.to_string(),
            CHECKOUT_WORKER_IMAGE.to_string(),
        ),
    }
}

/// The top-level `name:` key.
///
/// Without it compose names the project after the directory, so two
/// deployments in directories of the same name share every container name and
/// every named volume - a fresh `chaps up` then inherits the database of a
/// deployment it has never heard of. Compose takes the `name:` of the last
/// `-f` file that sets one, so every chaps-owned file carries the same value
/// and any subset of the `-f` list names the same project.
///
/// Empty for a deployment whose directory name compose can make no project
/// name out of at all; compose falls back to its own rule there, as it always
/// has.
pub(crate) fn project_name_block(project_name: Option<&str>) -> String {
    match project_name {
        Some(name) => format!("name: {name}\n"),
        None => String::new(),
    }
}

/// Render the generated `.env`.
pub fn render_env(spec: &EnvSpec) -> String {
    // An active line only when the tag says something `latest` does not.
    let chap_image_tag_line = match spec.chap_image_tag.as_deref() {
        Some(tag) if tag != "latest" => format!("CHAP_IMAGE_TAG={tag}"),
        _ => "# CHAP_IMAGE_TAG=latest".to_string(),
    };
    let pins = if spec.model_tag_pins.is_empty() {
        NO_TAG_PINS.to_string()
    } else {
        spec.model_tag_pins
            .iter()
            .map(|(var, tag)| format!("# {var}={tag}"))
            .collect::<Vec<_>>()
            .join("\n")
    };
    fill(
        &ENV_TEMPLATE,
        &[
            ("POSTGRES_USER", &spec.postgres_user),
            ("POSTGRES_PASSWORD", &spec.postgres_password),
            ("POSTGRES_DB", &spec.postgres_db),
            ("CHAP_IMAGE_TAG_LINE", &chap_image_tag_line),
            ("API_PORT", &spec.api_port.to_string()),
            (
                "CHAP_API_TOKEN_LINE",
                &secret_line(API_TOKEN_ENV_VAR, spec.api_token.as_deref()),
            ),
            (
                "REGISTRATION_KEY_LINE",
                &secret_line(REGISTRATION_KEY_ENV_VAR, spec.registration_key.as_deref()),
            ),
            ("MODEL_TAG_PINS", &pins),
        ],
    )
}

/// One secret's `.env` line: an active assignment when there is a value, and
/// otherwise the commented placeholder.
///
/// The placeholder is written even when the deployment has no authentication,
/// so the variable is discoverable where an operator would look for it, and so
/// `chaps auth enable` has a line to uncomment in place rather than appending
/// one at the bottom of the file.
fn secret_line(var: &str, value: Option<&str>) -> String {
    match value {
        Some(value) => format!("{var}={}", crate::dotenv::encode(value)),
        None => format!("# {var}="),
    }
}

/// Render `compose.ocs.yml`: the `ocs` component.
///
/// Three blocks are conditional. The host port is published only when the
/// component records one, so an instance behind a reverse proxy is `expose`d on
/// the compose network and nowhere else. The plugin mount appears only when the
/// project has an `ocs/plugins/` to mount, since compose fails to start a
/// service whose bind source does not exist. And the `S3_*` block only appears
/// when the `s3` component is on: OCS does not read those variables yet - it is
/// about to - so they are written as forward-looking settings with a comment
/// that says as much, rather than being left out until the day the contract
/// lands.
///
/// The five dataset credential variables are unconditional, all of them
/// `${VAR:-}`. OCS reads each one as `os.getenv(...) or <the file>`, so an empty
/// value is one it does not have: passing them always costs a deployment that
/// sets none of them nothing, and means the operator only ever has to put a
/// credential in `.env` rather than in `.env` and then in `.chaps/` as well.
pub fn render_ocs(spec: &OcsSpec) -> String {
    let s3_lines = if spec.s3 {
        format!(
            "      # Forward-looking: OCS does not read these yet.\n\
             \x20     S3_ENDPOINT: http://s3:{S3_CONTAINER_PORT}\n\
             \x20     {S3_ACCESS_KEY_ENV_VAR}: ${{{S3_ACCESS_KEY_ENV_VAR}:-}}\n\
             \x20     {S3_SECRET_KEY_ENV_VAR}: ${{{S3_SECRET_KEY_ENV_VAR}:-}}\n\
             \x20     S3_BUCKET: {S3_BUCKET}\n"
        )
    } else {
        String::new()
    };
    let mut data_source_lines = String::from(
        "      # Dataset credentials, empty unless .env sets them; see docs/components.md.\n",
    );
    for var in OCS_DATA_SOURCE_ENV_VARS {
        data_source_lines.push_str(&format!("      {var}: ${{{var}:-}}\n"));
    }
    let mut port_lines = format!("    expose:\n      - \"{OCS_CONTAINER_PORT}\"\n");
    if let Some(port) = spec.host_port {
        port_lines.push_str(&format!(
            "    ports:\n      - \"{port}:{OCS_CONTAINER_PORT}\"\n"
        ));
    }
    let plugins_line = if spec.plugins {
        format!("      - ./{OCS_DIR}/{OCS_PLUGINS_DIR}:{OCS_PLUGINS_TARGET}:ro\n")
    } else {
        String::new()
    };
    fill(
        &OCS_TEMPLATE,
        &[
            ("IMAGE", OCS_IMAGE),
            ("TAG_VAR", OCS_TAG_ENV_VAR),
            ("IMAGE_TAG", &spec.image_tag),
            ("PORT_LINES", &port_lines),
            ("CONTAINER_PORT", &OCS_CONTAINER_PORT.to_string()),
            ("BASE_URL_VAR", OCS_BASE_URL_ENV_VAR),
            ("BASE_URL", spec.base_url.as_deref().unwrap_or_default()),
            ("DATA_SOURCE_LINES", &data_source_lines),
            ("S3_LINES", &s3_lines),
            ("CONFIG_PATH", &format!("{OCS_DIR}/{OCS_CONFIG_FILE}")),
            ("PLUGINS_LINE", &plugins_line),
            ("VOLUME", OCS_VOLUME),
        ],
    )
}

